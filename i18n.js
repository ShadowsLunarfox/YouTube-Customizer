  function canonicalLanguage(value) {
    const tag = String(value || '').trim().replace(/_/g, '-').toLowerCase();
    if (/^(yue|zh-yue)(-|$)/.test(tag)) return 'yue-Hant';
    if (/^zh(-|$)/.test(tag)) return /-hant\b/.test(tag) || !/-hans\b/.test(tag) && /-(tw|hk|mo)\b/.test(tag) ? 'zh-TW' : 'zh-CN';
    if (/^ms(-|$)/.test(tag)) return 'ms-MY';
    if (/^(id|in)(-|$)/.test(tag)) return 'id';
    const base = tag.split('-')[0];
    return ['en', 'ja', 'ko', 'th'].includes(base) ? base : null;
  }
  let browserLanguageCache;
  function readBrowserLanguage() {
    if (browserLanguageCache !== undefined) return browserLanguageCache;
    // Old content-script callbacks can outlive extension reloads. Optional
    // chaining does not catch an API method throwing from an invalid context.
    try { browserLanguageCache = globalThis.chrome?.i18n?.getUILanguage?.(); } catch { /* Use navigator below. */ }
    browserLanguageCache ||= globalThis.navigator?.languages || globalThis.navigator?.language || 'en';
    return browserLanguageCache;
  }
  function resolveLanguage(preference, browserLanguage) {
    const explicit = canonicalLanguage(preference);
    if (explicit) return explicit;
    browserLanguage ??= readBrowserLanguage();
    for (const tag of Array.isArray(browserLanguage) ? browserLanguage : [browserLanguage]) {
      const language = canonicalLanguage(tag);
      if (language) return language;
    }
    return 'en';
  }
